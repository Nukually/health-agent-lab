import {
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core'
import type {
  CheckInA2uiSchema,
  CheckInAttachment,
  CheckInCardStatus,
  CheckInDisplayMode,
  CheckInRenderedA2uiSchema,
  CheckInValues,
} from '@health-agent/shared'
import { users } from './users.js'
import { chatSessions } from './sessions.js'
import { messages } from './messages.js'

export const userCheckInSchemas = pgTable(
  'user_check_in_schemas',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
    categoryKey: varchar('category_key', { length: 80 }).notNull(),
    categoryName: varchar('category_name', { length: 120 }).notNull(),
    displayMode: varchar('display_mode', { length: 20 }).$type<CheckInDisplayMode>().notNull().default('calendar'),
    categoryDescription: varchar('category_description', { length: 500 }),
    aliases: text('aliases').array().notNull().default([]),
    schemaVersion: integer('schema_version').notNull().default(1),
    schemaHash: varchar('schema_hash', { length: 80 }).notNull(),
    a2uiSchema: jsonb('a2ui_schema').$type<CheckInA2uiSchema>().notNull(),
    status: varchar('status', { length: 20 }).notNull().default('active'),
    createdFromSessionId: uuid('created_from_session_id').references(() => chatSessions.id, { onDelete: 'set null' }),
    createdFromMessageId: uuid('created_from_message_id').references(() => messages.id, { onDelete: 'set null' }),
    createdFromToolCallId: varchar('created_from_tool_call_id', { length: 120 }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
    lastUsedAt: timestamp('last_used_at', { withTimezone: true }),
  },
  (table) => [
    uniqueIndex('idx_user_check_in_schemas_user_category').on(table.userId, table.categoryKey),
    index('idx_user_check_in_schemas_user_updated').on(table.userId, table.updatedAt),
    index('idx_user_check_in_schemas_user_last_used').on(table.userId, table.lastUsedAt),
  ],
)

export const checkInRecords = pgTable(
  'check_in_records',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
    schemaId: uuid('schema_id').notNull().references(() => userCheckInSchemas.id, { onDelete: 'cascade' }),
    categoryKey: varchar('category_key', { length: 80 }).notNull(),
    schemaVersion: integer('schema_version').notNull().default(1),
    title: varchar('title', { length: 160 }).notNull(),
    recordedAt: timestamp('recorded_at', { withTimezone: true }).notNull(),
    recordedByType: varchar('recorded_by_type', { length: 20 }).notNull(),
    recordedByName: varchar('recorded_by_name', { length: 100 }).notNull(),
    sourceSessionId: uuid('source_session_id').references(() => chatSessions.id, { onDelete: 'set null' }),
    sourceMessageId: uuid('source_message_id').references(() => messages.id, { onDelete: 'set null' }),
    toolCallId: varchar('tool_call_id', { length: 120 }),
    valuesJson: jsonb('values_json').$type<CheckInValues>().notNull().default({}),
    attachmentsJson: jsonb('attachments_json').$type<CheckInAttachment[]>().notNull().default([]),
    renderedA2uiSchema: jsonb('rendered_a2ui_schema').$type<CheckInRenderedA2uiSchema>().notNull(),
    schemaSnapshot: jsonb('schema_snapshot').$type<CheckInA2uiSchema>().notNull(),
    tags: text('tags').array().notNull().default([]),
    dedupeKey: varchar('dedupe_key', { length: 80 }).notNull(),
    deletedAt: timestamp('deleted_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex('idx_check_in_records_user_dedupe').on(table.userId, table.dedupeKey),
    uniqueIndex('idx_check_in_records_session_tool').on(table.sourceSessionId, table.toolCallId),
    index('idx_check_in_records_user_recorded').on(table.userId, table.recordedAt),
    index('idx_check_in_records_user_category_recorded').on(table.userId, table.categoryKey, table.recordedAt),
  ],
)

export const checkInCards = pgTable(
  'check_in_cards',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
    sessionId: uuid('session_id').notNull().references(() => chatSessions.id, { onDelete: 'cascade' }),
    sourceMessageId: uuid('source_message_id').references(() => messages.id, { onDelete: 'set null' }),
    assistantMessageId: uuid('assistant_message_id').references(() => messages.id, { onDelete: 'set null' }),
    toolCallId: varchar('tool_call_id', { length: 120 }).notNull(),
    status: varchar('status', { length: 20 }).$type<CheckInCardStatus>().notNull().default('draft'),
    recordId: uuid('record_id').references(() => checkInRecords.id, { onDelete: 'set null' }),
    schemaActionHint: varchar('schema_action_hint', { length: 20 }).notNull(),
    existingSchemaId: uuid('existing_schema_id').references(() => userCheckInSchemas.id, { onDelete: 'set null' }),
    categoryName: varchar('category_name', { length: 120 }).notNull(),
    displayMode: varchar('display_mode', { length: 20 }).$type<CheckInDisplayMode>().notNull().default('calendar'),
    schemaJson: jsonb('schema_json').$type<CheckInA2uiSchema>().notNull(),
    valuesJson: jsonb('values_json').$type<CheckInValues>().notNull().default({}),
    attachmentsJson: jsonb('attachments_json').$type<CheckInAttachment[]>().notNull().default([]),
    note: text('note'),
    tags: text('tags').array().notNull().default([]),
    recordedAt: timestamp('recorded_at', { withTimezone: true }),
    sourceEvidenceJson: jsonb('source_evidence_json').$type<Record<string, string>>().notNull().default({}),
    missingFieldsJson: jsonb('missing_fields_json').$type<string[]>().notNull().default([]),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
    savedAt: timestamp('saved_at', { withTimezone: true }),
    deletedAt: timestamp('deleted_at', { withTimezone: true }),
  },
  (table) => [
    uniqueIndex('idx_check_in_cards_session_tool').on(table.sessionId, table.toolCallId),
    index('idx_check_in_cards_user_status_updated').on(table.userId, table.status, table.updatedAt),
    index('idx_check_in_cards_user_session_updated').on(table.userId, table.sessionId, table.updatedAt),
    index('idx_check_in_cards_record').on(table.recordId),
  ],
)
